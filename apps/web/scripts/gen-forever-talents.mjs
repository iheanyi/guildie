// Generates convex/shared/foreverTalents.ts: which class and talent tree each
// Forever talent (TraitDefinition ID, the same ID Blizzard's web API uses)
// belongs to. Source: wowsims/exporter Flavors/Forever/Talents.lua (MIT),
// itself generated from wowsims/forever. Re-run when Forever's talents change:
//   node scripts/gen-forever-talents.mjs
import { writeFileSync } from "node:fs";

const SOURCE = "https://raw.githubusercontent.com/wowsims/exporter/master/Flavors/Forever/Talents.lua";
const lua = await (await fetch(SOURCE)).text();
const block = lua.slice(lua.indexOf("-- BEGIN GENERATED TALENTS"), lua.indexOf("-- END GENERATED TALENTS"));
const commit = block.match(/Source: (\S+)/)?.[1] ?? "unknown";

const classes = {};
let current = null;
for (const line of block.split("\n")) {
	const cls = line.match(/^\s{4}([A-Z]+) = \{/);
	if (cls) {
		current = cls[1];
		classes[current] = [];
		continue;
	}
	const tree = line.match(/^\s*\{ ([\d, ]+) \}, -- (.+)$/);
	if (tree && current) {
		classes[current].push({ name: tree[2].trim(), ids: tree[1].split(",").map((n) => Number(n.trim())) });
	}
}
const count = Object.values(classes).flat().length;
if (Object.keys(classes).length !== 9 || count !== 27)
	throw new Error(`Unexpected shape: ${Object.keys(classes).length} classes, ${count} trees`);

const out = `// GENERATED by scripts/gen-forever-talents.mjs; don't edit.
// Source: ${SOURCE} (MIT), from ${commit}.
// Class token (UnitClass's English name) -> its talent trees in order, each with
// its talents' TraitDefinition IDs (the same IDs as Blizzard's web API).

export const FOREVER_TALENT_TREES: Record<string, { name: string; ids: number[] }[]> = ${JSON.stringify(classes, null, "\t")};

/** TraitDefinition ID -> its class token and tree. */
export const TALENT_TREE_BY_ID: Map<number, { classToken: string; tree: string; treeIndex: number }> = new Map(
	Object.entries(FOREVER_TALENT_TREES).flatMap(([classToken, trees]) =>
		trees.flatMap((tree, treeIndex) => tree.ids.map((id) => [id, { classToken, tree: tree.name, treeIndex }] as const)),
	),
);
`;
writeFileSync(new URL("../convex/shared/foreverTalents.ts", import.meta.url), out);
console.log(`wrote ${count} trees for ${Object.keys(classes).length} classes from ${commit}`);
